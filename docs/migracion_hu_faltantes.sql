-- HU30/HU44/HU47: aula actual de la persona (opcional)
ALTER TABLE persona ADD COLUMN IF NOT EXISTS id_aula bigint;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_persona_aula') THEN
        ALTER TABLE persona ADD CONSTRAINT fk_persona_aula FOREIGN KEY (id_aula) REFERENCES aulas (id_aula);
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_persona_id_aula ON persona (id_aula);

-- HU33/HU39/HU46: el perfil académico pertenece a un estudiante y guarda su estado psicológico
ALTER TABLE perfil_academico ADD COLUMN IF NOT EXISTS id_persona bigint;
ALTER TABLE perfil_academico ADD COLUMN IF NOT EXISTS estado_psicologico varchar(100);
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_perfil_academico_persona') THEN
        ALTER TABLE perfil_academico ADD CONSTRAINT fk_perfil_academico_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona);
    END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS ux_perfil_academico_id_persona ON perfil_academico (id_persona);

-- HU06: conectividad medida de cada escuela
